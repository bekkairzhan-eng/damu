// Категории, по которым у должности ещё не заполнен текст. Пустая строка
// считается незаполненной — поле обязательное.
export function missingReqs(position, categories) {
  return categories.filter(c => !(position.generalReqs?.[c.id] || '').trim())
}

export function isComplete(position, categories) {
  return missingReqs(position, categories).length === 0
}
