function buildInitialSkills() {
  let id = 1
  const skills = []
  for (const category of CATEGORIES) {
    for (const name of SKILLS_BY_CATEGORY[category] || []) {
      const seeded = SEEDED_CONTENT[name]
      skills.push({
        id: id++,
        name,
        category,
        approver: DEFAULT_APPROVER_BY_CATEGORY[category] || 'РП',
        description: seeded?.description || '',
        levels: seeded?.levels || emptyLevels(),
        materials: seeded?.materials || emptyMaterials(),
      })
    }
  }
  return skills
}

export const INITIAL_SKILLS = buildInitialSkills()

// Категория навыка всегда выводится из каталога, а не задаётся руками там,
// где навык упоминается (план развития, аттестация, требования к должности
// и т.п.) — иначе название/категория неизбежно расходятся с /skills.
export function categoryOf(name) {
  return INITIAL_SKILLS.find(s => s.name === name)?.category
}
